#' Create longitudinal summary line plots
#'
#' @description
#' Creates one line plot for each selected numeric variable measured over time.
#' The function can display mean or median trajectories, optional interquartile
#' range ribbons, observed data points, and individual subject trajectories.
#'
#' Plots can be generated overall or stratified by a grouping variable. The
#' output is either a "ggplot" object if only one variable is provided,
#' a list of "ggplot" objects if is provided more than one variable or, if
#' \code{pptx = TRUE}, a PowerPoint file.
#'
#' @param data A data frame containing the variables to plot.
#' @param variables Character vector containing all numeric variables of interest.
#' @param time Character string giving the name of the time variable. This
#'   variable has to be numeric because the function uses
#'   \code{scale_x_continuous()}. By default breaks and labels are set as the
#'   unique values of \code{time}, however it's possible to customize them with
#'   the \code{breaks} and the \code{labels} optional parameters: \code{breaks} must be a
#'   numeric vector and have the same length as \code{labels}, which can be either a
#'   numeric or a character vector.
#' @param group Factor identifying the grouping variable. Use \code{"Overall"}
#'   to generate a single trajectory without stratification.
#' @param statistic Character string indicating the summary statistic to plot.
#'   Allowed values are \code{"median"} and \code{"mean"} (Default =
#'   \code{"median"}).
#' @param ylim Numeric vector of length 2 giving the lower and upper quantiles
#'   used to determine the y-axis limits (Default = \code{c(0, 1)}).
#' @param loess Logical. If \code{TRUE}, applies a LOESS-smoothed line to the
#'   summary trajectory (Default = \code{FALSE}).
#' @param loess_span Controls the amount of smoothing for the default loess
#'   smoother. Smaller numbers produce wigglier lines, larger numbers produce
#'   smoother lines (Default = 1).
#' @param lwd Numeric. Line width of the summary trajectory (Default = 1).
#' @param alpha Numeric. Transparency of the summary trajectory (Default = 1).
#' @param ribbon Logical. If \code{TRUE}, adds a ribbon representing the
#'   interquartile range, from Q1 to Q3 (Default = \code{TRUE}).
#' @param alpha_ribbon Numeric. Transparency of the ribbon (Default = 0.5).
#' @param points Logical. If \code{TRUE}, adds observed data points (Default =
#'   \code{FALSE}). Additional characteristic can be specified with the
#'   \code{alpha_point} and the \code{size_point} parameters.
#' @param id_lines Logical. If \code{TRUE}, adds individual subject trajectories
#'   (Default = \code{FALSE}). Additional characteristic can be specified with
#'   the \code{alpha_id_lines} and the \code{lwd_id_lines} parameters.
#' @param id Column name of id variable used to connect paired observations
#'   (Default = \code{"ID"}).
#' @param Overall Logical. If \code{TRUE}, annotates each plot with an overall
#'   p-value from the \code{Test_results} argument in the upper-left corner (Default =
#'   \code{FALSE}. Text size for p-value annotation can be customised with the
#'   \code{posthoc_test_size} argument (Default = 3.88).
#' @param Posthoc Logical. If \code{TRUE}, adds post-hoc comparison annotations
#'   (Default = \code{FALSE}). Text size for p-value annotations can be
#'   customised with the \code{posthoc_test_size} argument (Default = 3.88).
#' @param Test_results Data frame containing overall and/or post-hoc test
#'   results generated by \code{LandS::cont_var_test()} and formatted using
#'   \code{LandS::posthoc_df()} (Default = \code{NULL}).
#'
#'   Required when either \code{Overall = TRUE} or \code{Posthoc = TRUE}.
#' @param threshold_posthoc Numeric. P-value threshold used to filter post-hoc
#'   comparisons (Default = 0.05).
#' @param overall_p Character identifying the p-value column of
#'   \code{Test_results} to display as overall test (Default =
#'   \code{"Overall.padj"}).
#' @param palette Character vector of colours used for groups. Its length must
#'   match the number of group levels when \code{group} is not set to
#'   \code{"Overall"} (Default = \code{"black"}).
#' @param grid Logical. If \code{TRUE}, uses the default grid-oriented theme
#'   (Default = \code{TRUE}). If \code{TRUE}, aspect ratio of the plot can be
#'   set with the \code{ratio} parameter (Default = 1).
#' @param pptx Logical. If \code{TRUE}, saves the plots to a PowerPoint file
#'   instead of returning them (Default = \code{FALSE}). Plot dimensions in
#'   inches can be specified with the \code{pptx_width} and the
#'   \code{pptx_height} parameters (Numeric with default = 8.5 and 5.5,
#'   respectively).
#' @param target Character string giving the output path for the PowerPoint file
#'   (Default = \code{"Lineplots.pptx"}).
#' @param label_legend_title A title for your list. Default sets "Lineplots by
#'   grouping variable" and the current date. The size of the title text can be
#'   specified with the \code{size_legend_title} parameter.
#' @param extra Logical. If \code{TRUE}, adds extra ggplot layers returned by
#' \code{extra_text} (Default = \code{FALSE}).
#' @param extra_text Function taking a variable name and returning one or more
#'   ggplot layers (Default = \code{NULL}).
#' @param col_title Logical. If \code{TRUE}, fills plot-title boxes using
#'   colours (Default = \code{FALSE}).
#' @param fill_title Function returning a fill colour for each variable name.
#'   Required when \code{col_title = TRUE} (Default = \code{NULL}). Additional
#'   transparency of the fill colour can be specified with the
#'   \code{alpha_fill_title} parameter (Default = 0.2). Additional title size
#'   can be set with the \code{size_title} parameter (Default = 7).
#' @param title_leg Logical. If \code{TRUE}, takes a variable name and matches a
#'   custom title for the corresponding plot (Default = \code{FALSE}).
#' @param title_legend Function taking a variable name and returning the title
#'   to display. Required when \code{title_leg = TRUE} (Default = \code{NULL}).
#'   Additional size of the title can be set with the \code{size_title}
#'   parameter (Default = 7).
#' @param verbose Logical. If \code{TRUE}, prints progress bar and messages
#'   (Default = \code{TRUE}).
#' @param ... Additional arguments passed to \code{theme_lands_grid()} or
#'   \code{theme_lands_pptx()}
#'
#' @return If \code{pptx = FALSE}, returns a single \code{ggplot} object when only one variable is
#' provided, otherwise a list of \code{ggplot} objects. When more
#' than one variable is supplied, the first element = a legend/title panel and
#' subsequent elements are the plots for each variable.
#'
#' If \code{pptx = TRUE}, the function writes a PowerPoint file to \code{target}
#' and returns \code{NULL} invisibly.
#'
#' @author Stefano Bergamini, Luca Lalli
#'
#' @examples
#' data_example <- data.frame(
#'   ID = rep(1:20, each = 4),
#'   Time = rep(0:3, times = 20),
#'   Group = rep(rep(c("A", "B"), each = 10), each = 4),
#'   marker1 = rnorm(80, mean = rep(0:3, times = 20)),
#'   marker2 = rnorm(80, mean = rep(0:3, times = 20) / 2)
#' )
#'
#' # One variable, overall median trajectory
#' Lineplots(
#'   data = data_example,
#'   variables = "marker1",
#'   time = "Time",
#'   group = "Overall",
#'   verbose = FALSE
#' )
#'
#' # Multiple variables stratified by group
#' plots_grouped <- Lineplots(
#'   data = data_example,
#'   variables = c("marker1", "marker2"),
#'   time = "Time",
#'   group = "Group",
#'   palette = c("salmon", "royalblue"),
#'   id_lines = TRUE,
#'   points = TRUE,
#'   verbose = FALSE
#' )
#'
#' plots_grouped[[2]]
#'
#' # Save to PowerPoint
#' \dontrun{
#' dir.create("Output")
#' Lineplots(
#'   data = data_example,
#'   variables = c("marker1", "marker2"),
#'   time = "Time",
#'   group = "Group",
#'   verbose = FALSE,
#'   pptx = TRUE,
#'   target = "Output/Lineplots.pptx"
#' )
#' }
#'
#' @export
#' @importFrom rlang .data
Lineplots <- function (data,
                       variables,
                       time,
                       group,

                       statistic = "median",
                       ylim = c(0, 1),
                       loess = FALSE,
                       loess_span = 1,
                       lwd = 1,
                       alpha = 1,

                       ribbon = TRUE,
                       alpha_ribbon = 0.5,

                       points = FALSE,

                       id_lines = FALSE,
                       id = "ID",

                       Overall = FALSE,
                       Posthoc = FALSE,
                       Test_results = NULL,
                       threshold_posthoc = 0.05,
                       overall_p = "Overall.padj",

                       palette = "black",

                       grid = TRUE,
                       pptx = FALSE,
                       target = "Lineplots.pptx",

                       label_legend_title = paste0("Lineplots by ", group, "\n", format(Sys.Date(), "%d/%m/%Y")),

                       extra = FALSE,
                       extra_text = NULL,
                       col_title = FALSE,
                       fill_title = NULL,
                       title_leg = FALSE,
                       title_legend = NULL,

                       verbose = TRUE,
                       ...)


{

  if ((Overall || Posthoc) && is.null(Test_results)) {
    stop("`Test_results` must be supplied when `Overall = TRUE` or `Posthoc = TRUE`.")
  }

  if (!is.numeric(data[[time]])) {
    stop("`time` must be numeric because the function uses scale_x_continuous().")
  }

  start_time <- Sys.time()
  lineplots <- list()

  if (grid) {
    graph_params <- set_params_grid(...)
  } else if (pptx) {
    graph_params <- set_params_pptx(...)
  }
  if(is.na(graph_params[["breaks"]])) {
    graph_params[["breaks"]] = sort(unique(data[[time]]))
  }
  if (is.na(graph_params[["labels"]])) {
    graph_params[["labels"]] = sort(unique(data[[time]]))
  }

  if (verbose) message(paste0("Creation ", length(variables), " lineplots with: \n",
                              "-Split by ", group, "\n",
                              "-Break time ", paste(graph_params[["breaks"]], collapse = ", "), "\n",
                              "-Label time ", paste(graph_params[["labels"]], collapse = ", "), "\n",
                              "-Stat Line: ", statistic, "\n",
                              "-Smooth Line: ", loess, "\n",
                              "-Ribbon: ", ribbon, "\n",
                              "-Points: ", points, "\n"
  ))

  if (length(variables) > 1) {
    lineplots[[1]] <- ggplot2::ggplot(data, ggplot2::aes(x = 1, y = 1)) +
      {
        if (!group == "Overall")
          ggplot2::geom_point(ggplot2::aes(colour = .data[[group]]),
                              alpha = 0, na.rm = TRUE, show.legend = TRUE)
      } + {
        if (group == "Overall")
          ggplot2::geom_point(alpha = 0, na.rm = TRUE, show.legend = TRUE)
      } + {
        if (!group == "Overall")
          ggplot2::scale_color_manual(values = palette)
      } + {
        if (group == "Overall")
          ggplot2::scale_color_manual(values = palette[1])
      } + {
        if (!group == "Overall")
          ggplot2::scale_fill_manual(values = palette)
      } + {
        if (group == "Overall")
          ggplot2::scale_fill_manual(values = palette[1])
      } +
      ggpubr::theme_transparent() +
      ggplot2::theme(legend.text = ggplot2::element_text(size = graph_params[["size_legend_text"]], face = "bold")) +
      ggplot2::annotate(geom = "text", x = 1, y = 1.001,
                        size = graph_params[["size_legend_title"]], label = label_legend_title,
                        vjust = 1.25, fontface = "bold") +
      ggplot2::guides(color = ggplot2::guide_legend(override.aes = list(size = 7.5, shape = 20))) +
      ggplot2::theme(legend.position = "inside", legend.justification = c(0.5, 0.3), legend.title = ggplot2::element_blank())

  } else { }

  for (i in variables) {
    if (col_title == TRUE) {
      fill.title <- fill_title(i)
    } else {
      fill.title <- "transparent"
    }
    k <- which(variables == i)
    if (Posthoc) {
      posthoc_df <- posthoc_df(Test_results = Test_results, data = data, group = time, threshold_posthoc = threshold_posthoc, i = i)
    }

    if (loess) {
      grouping <- time

      if (!group == "Overall") {
        grouping <- c(time, group)
      }
      # Define smooth data
      smooth_data <- data %>%
        dplyr::group_by(dplyr::across(dplyr::all_of(grouping))) %>%
        dplyr::summarise(
          smooth_y =
            if (statistic == "median") {
              stats::median(.data[[i]], na.rm = TRUE)
            } else {
              mean(.data[[i]], na.rm = TRUE)
            },
          Lower = stats::quantile(.data[[i]], 0.25, na.rm = TRUE),
          Upper = stats::quantile(.data[[i]], 0.75, na.rm = TRUE),
          .groups = "drop")
    }

    Quantiles <- data.frame(Times = unique(data[[time]]),
                            Inferior = tapply(data[[i]], data[[time]], FUN = function(z) stats::quantile(z, ylim[1], na.rm = TRUE)),
                            Superior = tapply(data[[i]], data[[time]], FUN = function(z) stats::quantile(z, ylim[2], na.rm = TRUE)))
    # Define ribbon data
    if (ribbon && loess && group == "Overall") {
      loess_upper <- stats::loess(stats::as.formula(paste("Upper ~", time)), data = smooth_data, span = loess_span)
      loess_lower <- stats::loess(stats::as.formula(paste("Lower ~", time)), data = smooth_data, span = loess_span)
      xseq <- seq(min(smooth_data[[time]]), max(smooth_data[[time]]), length.out = 50)
      ribbon_data <- data.frame(x = xseq,
                                ymin = stats::predict(loess_lower, xseq),
                                ymax = stats::predict(loess_upper, xseq))
    } else if (ribbon && loess && !group == "Overall") {
      ribbon_data <- smooth_data %>%
        dplyr::group_by(.data[[group]]) %>%
        dplyr::group_modify(~{
          loess_upper <- stats::loess(Upper ~ .x[[time]], data = .x, span = loess_span)
          loess_lower <- stats::loess(Lower ~ .x[[time]], data = .x, span = loess_span)
          xseq <- seq(min(.x[[time]]), max(.x[[time]]), length.out = 50)
          data.frame(x = xseq, y = i,
                     ymin = predict(loess_lower, xseq), ymax = predict(loess_upper, xseq))}
        ) %>%
        dplyr::ungroup()
    }

    # Define the graph
    gg <-
      ggplot2::ggplot(data = data, ggplot2::aes(x = .data[[time]], y = .data[[i]])) +
      ggplot2::coord_cartesian(ylim = c(min(Quantiles$Inferior), max(Quantiles$Superior))) +
      {
        if (group == "Overall")
          ggplot2::aes(colour = "black")
      } + {
        if (!group == "Overall")
          ggplot2::aes(colour = .data[[group]], fill = .data[[group]])
      } + {
        if (points)
          ggplot2::geom_point(size = graph_params[["size_point"]],
                              alpha = graph_params[["alpha_point"]],
                              shape = 19)
      } + {
        if (id_lines)
          ggplot2::geom_line(ggplot2::aes(y = .data[[i]], group = .data[[id]]),
                             alpha = graph_params[["alpha_id_lines"]],
                             linewidth = graph_params[["lwd_id_lines"]],
                             colour = "black")
      } + {
        if (loess)
          ggplot2::stat_smooth(data = smooth_data,
                               ggplot2::aes(x = .data[[time]], y = .data[["smooth_y"]]),
                               geom = "line", alpha = alpha,
                               size = lwd, span = loess_span,
                               method = "loess", formula = 'y ~ x',
                               show.legend = FALSE)
      } + {
        if (!loess & statistic == "median")
          ggplot2::stat_summary(geom = "line", fun = stats::median,
                                alpha = alpha, linewidth = lwd,
                                show.legend = FALSE)
      } + {
        if (!loess & statistic == "mean")
          ggplot2::stat_summary(geom = "line", fun = mean,
                                alpha = alpha, linewidth = lwd,
                                show.legend = FALSE)

      } + {
        if (Overall)
          ggplot2::annotate(geom = "text", x = -Inf, y = Inf,
                            hjust = -0.1, vjust = 1.5,
                            size = graph_params[["posthoc_test_size"]],
                            label = formatz_p(Test_results[Test_results[["Variable"]] == i, overall_p]),
                            colour = "black")
      } + {
        if (Posthoc)
          if (nrow(posthoc_df) > 0 & !all(is.na(posthoc_df)))
            ggpubr::stat_pvalue_manual(posthoc_df, label = "p = {pvalue}",
                                       bracket.shorten = graph_params[["bracket_shorten"]],
                                       bracket.nudge.y = graph_params[["bracket.nudge.y"]],
                                       y.position = max(tapply(data[[i]], data[[time]], stats::median, na.rm = T)),
                                       step.increase = 0.08,
                                       size = graph_params[["posthoc_test_size"]])
      } + {
        if (extra)
          extra_text(i)
      } + {
        if (ribbon && loess && group == "Overall")
          ggplot2::geom_ribbon(data = ribbon_data, ggplot2::aes(x = .data[["x"]], ymin = .data[["ymin"]], ymax = .data[["ymax"]]),
                               alpha = alpha_ribbon, fill = palette, show.legend = FALSE, colour = NA, inherit.aes = FALSE)
      } + {
        if (ribbon && loess && !group == "Overall")
          ggplot2::geom_ribbon(data = ribbon_data, ggplot2::aes(x = .data[["x"]], ymin = .data[["ymin"]], ymax = .data[["ymax"]], fill = .data[[group]]),
                               alpha = alpha_ribbon, show.legend = FALSE, colour = NA, inherit.aes = FALSE)
      } + {
        if (ribbon && !loess && group == "Overall")
          ggplot2::stat_summary(ggplot2::aes(x = .data[[time]], y = .data[[i]]),
                                geom = "ribbon", alpha = alpha_ribbon, linewidth = NA,
                                fun.min = function(z) stats::quantile(z, 0.25),
                                fun.max = function(z) stats::quantile(z, 0.75), inherit.aes = FALSE)
      } + {
        if (ribbon && !loess && !group == "Overall")
          ggplot2::stat_summary(ggplot2::aes(x = .data[[time]], y = .data[[i]], fill = .data[[group]]),
                                geom = "ribbon", alpha = alpha_ribbon, linewidth = NA,
                                fun.min = function(z) stats::quantile(z, 0.25),
                                fun.max = function(z) stats::quantile(z, 0.75), inherit.aes = FALSE)

      } +
      ggplot2::scale_color_manual(values = palette, drop = FALSE) +
      ggplot2::scale_fill_manual(values = palette, drop = FALSE, guide = "none") +
      ggplot2::scale_x_continuous(breaks = graph_params[["breaks"]],
                                  labels = graph_params[["labels"]],
                                  guide = ggplot2::guide_axis(check.overlap = TRUE)) +
      {

        if (title_leg){
          ggplot2::labs(title = title_legend(i), x = NULL, y = NULL)
        } else {
          ggplot2::labs(title = i, x = NULL, y = NULL)
        }

      } + {
        if (grid)
          theme_lands_grid(... = ...)
      } + {
        if (pptx)
          theme_lands_pptx(... = ...)
      }

    if (length(variables) > 1) {
      lineplots[[k + 1]] <- gg
    } else {
      lineplots[[k]] <- gg
    }
    if (verbose) Progress_bar(current = which(i == variables),
                              total = length(variables),
                              start_time = start_time,
                              bar_fill = "\U2588",
                              bar_void = "\U2591")
  }
  if (pptx) {
    ppt <- officer::read_pptx()
    if (verbose) message("Printing PowerPoint")
    for (i in 1:length(lineplots)) {
      lineplots[[i]] <- rvg::dml(ggobj = lineplots[[i]])
      ppt = officer::add_slide(ppt, layout = "Title and Content")
      officer::ph_with(ppt, lineplots[[i]],
                       officer::ph_location(width = graph_params[["pptx_width"]],
                                            height = graph_params[["pptx_height"]]))
    }
    print(ppt, target = target)
    if (verbose) message("Done printing :)")

  } else if (length(lineplots) == 1 && !pptx) {

    return(lineplots[[1]])

  } else {
    return(lineplots)
  }
}
